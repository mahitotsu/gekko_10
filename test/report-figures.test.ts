import { existsSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import type { Analysis } from "../scripts/analyze.js";
import { figures, groupedColumns, stackedColumns } from "../scripts/report-figures.js";

const RESULTS = "results/measurement-20261020/analysis.json";

describe("groupedColumns", () => {
  const chart = {
    title: "t",
    desc: "d",
    yLabel: "y",
    groups: [["A"], ["B"]],
    series: [
      { name: "Event", cls: "s1" as const, values: [10, 5] },
      { name: "Web", cls: "s2" as const, values: [2, null] },
    ],
    yMax: 10,
    ticks: [0, 10],
    fmt: (n: number) => String(n),
  };
  const svg = groupedColumns(chart);

  it("draws one bar per value, none for a missing one, with the value at the cap and a legend", () => {
    expect(svg.match(/<path class="s[12]"/g)).toHaveLength(3);
    expect(svg).toContain(">Event<");
    expect(svg).toContain(">Web<");
    expect(svg).toContain(">10<");
  });

  it("has a title and description for screen readers, and a dark-mode style", () => {
    expect(svg).toContain('<title id="t">t</title>');
    expect(svg).toContain('<desc id="d">d</desc>');
    expect(svg).toContain("prefers-color-scheme: dark");
  });

  it("escapes text", () => {
    expect(groupedColumns({ ...chart, groups: [["a<b"], ["&"]] })).toContain("a&lt;b");
  });
});

describe("stackedColumns", () => {
  it("draws the segments with a gap, the total at the cap, and skips the label of a segment too narrow to hold it", () => {
    const svg = stackedColumns({
      title: "t",
      desc: "d",
      bars: [{ label: "Event", segments: [{ name: "a", cls: "s3", ms: 10 }, { name: "b", cls: "s4", ms: 0.1 }, { name: "c", cls: "s5", ms: 3 }] }],
      yLabel: "y",
      yMax: 18,
      ticks: [0, 18],
    });
    expect(svg).toContain(">13.1<");
    expect(svg).toContain(">10.0<");
    expect(svg).not.toContain(">0.1<");
  });
});

describe("the report's figures", () => {
  it.skipIf(!existsSync(RESULTS))("are regenerated byte for byte from the measurement's analysis.json", () => {
    const analysis = JSON.parse(readFileSync(RESULTS, "utf8")) as Analysis;
    const made = figures(analysis);
    expect(Object.keys(made).sort()).toEqual(["fig1-cost.svg", "fig2-latency.svg", "fig3-saturation.svg", "fig4-environments.svg", "fig5-connections.svg"]);
    for (const [name, svg] of Object.entries(made)) expect(readFileSync(`docs/figures/${name}`, "utf8")).toBe(svg);
    expect(figures(analysis)).toEqual(made);
  });
});
